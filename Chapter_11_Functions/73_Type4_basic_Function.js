// Type 4 - with arg/ with return value

function sumofTwoNumbers(num1, num2){
    return num1 + num2;
}   

let c = sumofTwoNumbers(10, 20);
console.log(c);  // 30          

// you can also directly call the function inside console.log() without storing it in a variable
console.log(sumofTwoNumbers(10, 20));  // 30

