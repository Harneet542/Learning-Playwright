// type 4 - with template literal example (template literal is a way to create strings in JavaScript using 
// backticks and allows for embedding expressions inside the string using ${} syntax)

function greet(name)   {
    return `Hello, ${name}! Welcome to the world of template literals.`;
}
let op = greet('Alice');  // Hello, Alice! Welcome to the world of template literals.    
console.log(op);  // Hello, Alice! Welcome to the world of template literals.


