let arr =[1,2,3]

console.log(arr);


// add to end 
let arr =[1,2,3]
arr.push(4);
console.log(arr);

// remove element 
let arr =[1,2,3]
arr.pop()
console.log(arr);

// add element to start
let arr =[1,2,3]   // it takes element not the index
arr.unshift(0);
console.log(arr);

// remove element from start
let arr =[1,2,3]
arr.shift();
console.log(arr);

// remove and add element at a specific index
let arr =[1,5,3,4,2]
arr.splice(1,4,5,6);
console.log(arr);

